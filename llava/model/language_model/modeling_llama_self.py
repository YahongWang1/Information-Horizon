def get_token_list(size, x, y):
    if size == 0 or x == 0 or y == 0:
        return []
    else:
        token_list=[]
        for i in range(size):
            for j in range(size):
                start_idx = (x-1)*size + (y-1)*size*24 + i*24 + j
                token_list.append(start_idx)

        return token_list




